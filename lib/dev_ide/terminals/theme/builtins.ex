  @spec ids() :: [String.t()]
  def ids, do: Enum.map(@catalog, & &1.id)

  @spec list() :: [map()]
  def list do
    Enum.map(@catalog, fn %{id: id, label: label, detail: detail} ->
      %{id: id, label: label, detail: detail}
    end)
  end

  @spec variant_key(String.t(), :dark | :light) :: atom() | nil
  def variant_key(preset_id, scheme) do
    case Enum.find(@catalog, &(&1.id == preset_id)) do
      nil -> nil
      entry -> if(scheme == :dark, do: entry.dark, else: entry.light)
    end
  end

  @spec fetch_variant(atom()) :: map() | nil
  def fetch_variant(key) when is_atom(key), do: Map.get(variants(), key)

  defp variants, do: @variants

  @spec pad_grays([String.t()]) :: [String.t()]
  def pad_grays(colors), do: padded_grays(colors)

  defp padded_grays(colors) do
    last = List.last(colors) || "#cdd6f4"

    (colors ++ List.duplicate(last, max(0, 24 - length(colors))))
    |> Enum.take(24)
  end
